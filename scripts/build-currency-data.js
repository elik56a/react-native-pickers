// Generates src/currency/data.ts: the currencies countries use today (from countries-list, a dev dependency), with their
// English name, narrow symbol and decimal places from Node's full ICU, which Hermes lacks.
// Format: one record per line: code \t name \t symbol \t decimals \t flag country ('' for none)
const fs = require('node:fs');
const path = require('node:path');
const countries = JSON.parse(fs.readFileSync(require.resolve('countries-list').replace(/cjs[\\/].*$/, 'countries.min.json'), 'utf8'));

// A currency code starts with its country's code (USD, GBP), except these.
const FLAG_OVERRIDES = { EUR: 'EU' };

const names = new Intl.DisplayNames('en', { type: 'currency' });
const symbolOf = (code) =>
  new Intl.NumberFormat('en', { style: 'currency', currency: code, currencyDisplay: 'narrowSymbol' })
    .formatToParts(1)
    .find((p) => p.type === 'currency').value;
const decimalsOf = (code) => new Intl.NumberFormat('en', { style: 'currency', currency: code }).resolvedOptions().maximumFractionDigits;
const flagOf = (code) => FLAG_OVERRIDES[code] ?? (countries[code.slice(0, 2)] ? code.slice(0, 2) : '');

// Fund codes for accounting, not money people pay with.
const FUND_CODES = new Set(['BOV', 'CHE', 'CHW', 'CLF', 'COU', 'MXV', 'USN', 'UYI', 'UYW']);

const codes = [...new Set(Object.values(countries).flatMap((c) => c.currency))].filter((c) => !FUND_CODES.has(c)).sort();
const lines = codes.map((code) => [code, names.of(code), symbolOf(code), decimalsOf(code), flagOf(code)].join('\t'));
const out =
  '// AUTO-GENERATED by scripts/build-currency-data.js. Do not edit.\n' +
  '/* eslint-disable */\n' +
  `export type CurrencyCode =\n${codes.map((c) => `  | '${c}'`).join('\n')};\n\n` +
  'export const RAW_CURRENCY_DATA: string = ' +
  JSON.stringify(lines.join('\n')) +
  ';\n';
fs.writeFileSync(path.join(__dirname, '../src/currency/data.ts'), out);
console.log(lines.length, 'currencies,', (out.length / 1024).toFixed(0), 'KB');
