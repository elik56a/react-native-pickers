// Generates src/country/data.ts from countries-list (dev dependency only).
// Format: one record per line: code \t name \t native name \t aliases (|) \t dial codes (,)
const fs = require('node:fs');
const path = require('node:path');
const countries = JSON.parse(fs.readFileSync(require.resolve('countries-list').replace(/cjs[\\/].*$/, 'countries.min.json'), 'utf8'));

// Kosovo's code is +383; the others countries-list lists are its pre-2017 Monaco, Serbia and Slovenia codes.
const DIAL_OVERRIDES = { XK: [383] };

// North American numbers are +1 plus an area code: 1809 reads as "+1 809".
const formatDial = (n) => {
  const s = String(n);
  return s.length === 4 && s.startsWith('1') ? `+1 ${s.slice(1)}` : `+${s}`;
};

const codes = Object.keys(countries).sort();
const lines = codes.map((code) => {
  const c = countries[code];
  const native = c.native === c.name ? '' : c.native;
  const aliases = (c.alias || []).filter((a) => a !== code && a !== c.name).join('|');
  const dials = (DIAL_OVERRIDES[code] || c.phone).map(formatDial).join(',');
  return [code, c.name, native, aliases, dials].join('\t');
});
const out =
  '// AUTO-GENERATED by scripts/build-country-data.js from countries-list. Do not edit.\n' +
  '/* eslint-disable */\n' +
  `export type CountryCode =\n${codes.map((c) => `  | '${c}'`).join('\n')};\n\n` +
  'export const RAW_COUNTRY_DATA: string = ' +
  JSON.stringify(lines.join('\n')) +
  ';\n';
fs.writeFileSync(path.join(__dirname, '../src/country/data.ts'), out);
console.log(lines.length, 'countries,', (out.length / 1024).toFixed(0), 'KB');
