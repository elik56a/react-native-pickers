// Generates src/timezone/data.ts from Node's ICU (Intl.supportedValuesOf), since Hermes can't list time zones.
// Format: one zone per line: current IANA name \t the older name ICU and some browsers still use, if any.
const fs = require('node:fs');
const path = require('node:path');

// ICU keeps these pre-rename IANA names; phones report the current ones.
const RENAMED = {
  'Africa/Asmera': 'Africa/Asmara',
  'America/Buenos_Aires': 'America/Argentina/Buenos_Aires',
  'America/Catamarca': 'America/Argentina/Catamarca',
  'America/Coral_Harbour': 'America/Atikokan',
  'America/Cordoba': 'America/Argentina/Cordoba',
  'America/Godthab': 'America/Nuuk',
  'America/Indianapolis': 'America/Indiana/Indianapolis',
  'America/Jujuy': 'America/Argentina/Jujuy',
  'America/Louisville': 'America/Kentucky/Louisville',
  'America/Mendoza': 'America/Argentina/Mendoza',
  'Asia/Calcutta': 'Asia/Kolkata',
  'Asia/Katmandu': 'Asia/Kathmandu',
  'Asia/Rangoon': 'Asia/Yangon',
  'Asia/Saigon': 'Asia/Ho_Chi_Minh',
  'Atlantic/Faeroe': 'Atlantic/Faroe',
  'Europe/Kiev': 'Europe/Kyiv',
  'Pacific/Enderbury': 'Pacific/Kanton',
  'Pacific/Ponape': 'Pacific/Pohnpei',
  'Pacific/Truk': 'Pacific/Chuuk',
};

const lines = Intl.supportedValuesOf('timeZone')
  .map((id) => (RENAMED[id] ? [RENAMED[id], id] : [id, '']))
  .sort(([a], [b]) => (a < b ? -1 : 1))
  .map((fields) => fields.join('\t'));
const out =
  '// AUTO-GENERATED by scripts/build-timezone-data.js from ICU. Do not edit.\n' +
  '/* eslint-disable */\n' +
  `export const RAW_TIME_ZONE_DATA: string = ${JSON.stringify(lines.join('\n'))};\n`;
fs.writeFileSync(path.join(__dirname, '../src/timezone/data.ts'), out);
console.log(lines.length, 'time zones,', (out.length / 1024).toFixed(0), 'KB');
