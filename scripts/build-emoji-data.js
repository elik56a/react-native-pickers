// Generates src/emoji/data.ts from emojibase-data (dev dependency only).
// Format: one record per line: group \t emoji \t label \t tags \t version \t skins(comma)
const fs = require('fs');
const path = require('path');
const data = require('emojibase-data/en/data.json');
const lines = [];
for (const e of data) {
  if (e.group === undefined || e.group === 2) continue; // skip "component" (bare skin tones, hair)
  let skins = '';
  if (e.skins) {
    const single = e.skins.filter((s) => !Array.isArray(s.tone));
    if (single.length === 5) skins = single.sort((a, b) => a.tone - b.tone).map((s) => s.emoji).join(',');
  }
  const tags = (e.tags || []).filter((t) => !e.label.includes(t)).join(' ');
  lines.push([e.group, e.emoji, e.label, tags, e.version, skins].join('\t'));
}
const out =
  '// AUTO-GENERATED by scripts/build-emoji-data.js from emojibase-data. Do not edit.\n' +
  '/* eslint-disable */\n' +
  'export const RAW_EMOJI_DATA: string = ' + JSON.stringify(lines.join('\n')) + ';\n';
fs.writeFileSync(path.join(__dirname, '../src/emoji/data.ts'), out);
console.log(lines.length, 'emojis,', (out.length / 1024).toFixed(0), 'KB');
